interface AdaptiveStepServerDto {
  stepNumber: number
  title: string
  objective: string
  actionType: string
  targetRoute: string
  lessonId?: string
  priority: string
  isCompleted: boolean
}

interface AdaptiveLearningPathServerDto {
  id: string
  userId: string
  subjectId: string
  currentStage: string
  stageDescription: string
  shortTermGoals: string[]
  steps: AdaptiveStepServerDto[]
  generatedAt: string
}

/**
 * Returns overall milestone learning path data (for exam countdown / stages).
 */
export async function getLearningPath(): Promise<LearningPathData> {
  const authUser = getAuthUser()
  if (authUser) {
    try {
      const [stats, adaptive] = await Promise.all([
        apiClient.get<{ accuracyRate?: number; streakDays?: number; completedLessons?: number }>(
          '/api/v1/practice/dashboard-stats'
        ),
        apiClient.get<AdaptiveLearningPathServerDto>('/api/v1/ai/learning-path'),
      ])

      const progress = stats?.accuracyRate ? Math.round(stats.accuracyRate) : 0
      const streak = stats?.streakDays ?? 0

      // Map real adaptive steps into stages if generated by backend
      const stages: LearningPathStage[] =
        adaptive?.steps && adaptive.steps.length > 0
          ? adaptive.steps.map((st, idx) => ({
              id: `step-${st.stepNumber}`,
              orderNumber: st.stepNumber,
              title: st.title,
              status: st.isCompleted ? 'completed' : idx === 0 ? 'current' : 'upcoming',
              progress: st.isCompleted ? 100 : idx === 0 ? Math.min(progress, 50) : 0,
              estimatedHours: 2,
              completedLessons: st.isCompleted ? 1 : 0,
              totalLessons: 1,
              keyTopics: [st.objective],
              primaryLessonId: st.lessonId,
            }))
          : []

      const firstActionable = adaptive?.steps?.find((s) => !s.isCompleted) || adaptive?.steps?.[0]
      const aiSuggestion: AISuggestion | null = firstActionable
        ? {
            id: `sug-${firstActionable.stepNumber}`,
            title: firstActionable.title,
            reason: firstActionable.objective,
            actionLabel: 'Bắt đầu',
            actionUrl: firstActionable.targetRoute,
            topic:
              adaptive?.currentStage === 'remediation'
                ? 'Củng cố kiến thức hổng'
                : 'Tiếp tục lộ trình chuẩn GDPT 2018',
          }
        : null

      const now = new Date()
      const targetYear = now.getMonth() >= 8 ? now.getFullYear() + 1 : now.getFullYear()
      const examDate = new Date(targetYear, 5, 27)
      const dynamicDaysRemaining = Math.max(0, Math.ceil((examDate.getTime() - now.getTime()) / (1000 * 60 * 60 * 24)))

      return {
        goalTitle: `Mục tiêu điểm số THPT Lớp ${authUser.grade || '12'}`,
        targetExam: 'Kỳ thi Tốt nghiệp THPT Quốc gia',
        daysRemaining: dynamicDaysRemaining,
        overallProgress: progress,
        currentStreak: streak,
        stages,
        aiSuggestion: aiSuggestion as AISuggestion,
      }
    } catch {
      throw new Error('Không thể tải dữ liệu lộ trình học tập từ máy chủ. Vui lòng thử lại.')
    }
  }

  return {
    goalTitle: 'Lộ trình chuẩn GDPT 2018',
    targetExam: 'Kỳ thi Tốt nghiệp THPT',
    daysRemaining: 0,
    overallProgress: 0,
    currentStreak: 0,
    stages: [],
    aiSuggestion: null as unknown as AISuggestion,
  }
}

/**
 * Returns a personalized learning path for a given subject.
 */
export async function getSubjectLearningPath(subjectId: string): Promise<SubjectLearningPath> {
  const detail = await curriculumService.getSubject(subjectId)
  const subjectName = detail.name
  const grade = detail.grade

  if (!detail.chapters || detail.chapters.length === 0) {
    return {
      subjectId,
      subjectName,
      grade,
      totalLessons: 0,
      completedLessons: 0,
      overallProgress: 0,
      recommendedLesson: null,
      chapters: [],
      allCompleted: false,
    }
  }

  const allProgress = learningProgressRepository.getAll()

  let totalLessonCount = 0
  let completedLessonCount = 0
  const flatLessons: LearningPathLessonItem[] = []

  const chapters: LearningPathChapterItem[] = detail.chapters.map((chap, chapIdx) => {
    let chapCompleted = 0
    const chapLessons: LearningPathLessonItem[] = chap.lessons.map((les, lesIdx) => {
      totalLessonCount++
      const progressRecord = allProgress[les.id]
      const progress = progressRecord?.overallProgress ?? 0
      
      let status: LessonPathStatus = 'not-started'
      if (progress >= 100) {
        status = 'completed'
        chapCompleted++
        completedLessonCount++
      } else if (progress > 0) {
        status = 'in-progress'
      }

      const item: LearningPathLessonItem = {
        id: les.id,
        subjectId,
        chapterId: chap.id,
        chapterTitle: chap.title,
        title: les.title,
        order: (chapIdx + 1) * 100 + (lesIdx + 1),
        durationMinutes: 0,
        xp: 0,
        status,
        progress,
        lastActiveSectionId: progressRecord?.lastActiveSectionId,
      }

      flatLessons.push(item)
      return item
    })

    const chapTotal = chapLessons.length
    const chapProgressPercent = chapTotal > 0 ? Math.round((chapCompleted / chapTotal) * 100) : 0

    return {
      id: chap.id,
      title: chap.title,
      order: chapIdx + 1,
      totalLessons: chapTotal,
      completedLessons: chapCompleted,
      progressPercent: chapProgressPercent,
      lessons: chapLessons,
    }
  })

  const overallProgress = totalLessonCount > 0 ? Math.round((completedLessonCount / totalLessonCount) * 100) : 0
  const allCompleted = totalLessonCount > 0 && completedLessonCount === totalLessonCount

  let recommendedLesson: LearningPathLessonItem | null = null

  if (!allCompleted && flatLessons.length > 0) {
    // Priority 1: In-progress lesson (in-progress dở dang), sorted by updatedAt desc if available
    const inProgressLessons = flatLessons.filter((l) => l.status === 'in-progress')
    if (inProgressLessons.length > 0) {
      inProgressLessons.sort((a, b) => {
        const timeA = allProgress[a.id]?.updatedAt ? new Date(allProgress[a.id].updatedAt).getTime() : 0
        const timeB = allProgress[b.id]?.updatedAt ? new Date(allProgress[b.id].updatedAt).getTime() : 0
        return timeB - timeA
      })
      recommendedLesson = inProgressLessons[0]
    }

    // Priority 2: Next unstarted lesson right after completed lessons in sequence
    if (!recommendedLesson) {
      const firstUnstarted = flatLessons.find((l) => l.status === 'not-started')
      if (firstUnstarted) {
        recommendedLesson = firstUnstarted
      }
    }

    // Priority 3: Fallback to the first lesson if none matched
    if (!recommendedLesson) {
      recommendedLesson = flatLessons[0]
    }
  }

  // Mark recommended
  if (recommendedLesson) {
    recommendedLesson.isRecommendedNext = true
  }

  return {
    subjectId,
    subjectName,
    grade,
    totalLessons: totalLessonCount,
    completedLessons: completedLessonCount,
    overallProgress,
    recommendedLesson,
    chapters,
    allCompleted,
  }
}

/**
 * Returns the recommended "Continue Learning" target across all subjects.
 * Used by Dashboard ContinueLearningCard.
 */
export function getContinueLearningTarget(): ContinueLearningTarget | null {
  const allProgress = learningProgressRepository.getAll()
  const inProgressRecords = Object.values(allProgress)
    .filter((p) => p.overallProgress > 0 && p.overallProgress < 100)
    .sort((a, b) => {
      const timeA = a.updatedAt ? new Date(a.updatedAt).getTime() : 0
      const timeB = b.updatedAt ? new Date(b.updatedAt).getTime() : 0
      return timeB - timeA
    })

  if (inProgressRecords.length > 0) {
    const record = inProgressRecords[0]
    return {
      lessonId: record.lessonId,
      subjectId: record.subjectId,
      lessonTitle: record.lastActiveSectionTitle || record.lessonId,
      subjectName: record.subjectId,
      sectionId: record.lastActiveSectionId,
      sectionTitle: record.lastActiveSectionTitle,
      progress: record.overallProgress,
      lastActivityAt: record.updatedAt || new Date().toISOString(),
    }
  }

  return null
}

/**
 * Fetch real personalized adaptive learning path from backend
 */
export async function fetchAdaptiveLearningPath(subjectId?: string): Promise<any> {
  const authUser = getAuthUser()
  const targetSubject = resolveSubjectId({ subjectId, grade: authUser?.grade })
  if (!targetSubject) return null
  try {
    const res = await apiClient.get<any>(`/api/v1/ai/learning-path?subjectId=${targetSubject}`)
    if (res) return res
  } catch {
    // Graceful fallback
  }
  return null
}
